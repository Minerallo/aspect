def free_memory_percent() -> int | None:
    result = subprocess.run(["memory_pressure"], capture_output=True, text=True)
    match = re.search(r"System-wide memory free percentage: (\d+)%", result.stdout)
    return int(match.group(1)) if match else None


def run_monitored(
    command, working_directory, log_path, environment, minimum_free_percent
):
    available = free_memory_percent()
    if available is not None and available < minimum_free_percent:
        raise RuntimeError(f"not starting because only {available}% of memory is free")
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with log_path.open("w", encoding="utf-8") as log:
        process = subprocess.Popen(
            command,
            cwd=working_directory,
            env=environment,
            stdout=log,
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )
        while process.poll() is None:
            time.sleep(5)
            available = free_memory_percent()
            if available is not None and available < minimum_free_percent:
                os.killpg(process.pid, signal.SIGTERM)
                try:
                    process.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    os.killpg(process.pid, signal.SIGKILL)
                    process.wait()
                raise RuntimeError(
                    f"stopped {command[0]} because free memory fell to {available}%"
                )
        if process.returncode:
            raise subprocess.CalledProcessError(process.returncode, command)


def prepare_climate_case(template: Path, destination: Path, executable: Path) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    for namelist in template.glob("*.nml"):
        shutil.copy2(namelist, destination / namelist.name)
    for name in ("input", "maps", "restart"):
        source, target = template / name, destination / name
        if target.exists() or target.is_symlink():
            target.unlink()
        target.symlink_to(source.resolve(), target_is_directory=True)
    target = destination / "climber.x"
    if target.exists() or target.is_symlink():
        target.unlink()
    target.symlink_to(executable.resolve())


def run_climate(
    case, output_exchange, topography_exchange, climber_library, minimum_free_percent
):
    environment = os.environ.copy()
    paths = [str(climber_library), "/opt/homebrew/Cellar/netcdf/4.9.3/lib"]
    if environment.get("DYLD_LIBRARY_PATH"):
        paths.append(environment["DYLD_LIBRARY_PATH"])
    environment["DYLD_LIBRARY_PATH"] = ":".join(paths)
    environment["OMP_NUM_THREADS"] = "1"
    environment["CLIMBERX_CLIMATE_EXCHANGE_FILE"] = str(output_exchange.resolve())
    if topography_exchange is not None:
        environment["CLIMBERX_TOPOGRAPHY_EXCHANGE_FILE"] = str(
            topography_exchange.resolve()
        )
    run_monitored(
        ["./climber.x"], case, case / "climber.log", environment, minimum_free_percent
    )
    log_text = (case / "climber.log").read_text(encoding="utf-8", errors="replace")
    if (
        not output_exchange.is_file()
        or "run aborted because of instabilities" in log_text
    ):
        raise RuntimeError(
            f"CLIMBER-X did not complete a stable exchange; see {case / 'climber.log'}"
        )


