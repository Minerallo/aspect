def convert_climate(exchange: Path, fields: Path) -> None:
    fields.mkdir(parents=True, exist_ok=True)
    command = [sys.executable, str(EXCHANGE_TOOL), "climate-to-aspect", str(exchange)]
    for option, name in (
        ("--surface-topography", "surface-topography.txt"),
        ("--erosion-strength", "erosion-strength.txt"),
        ("--surface-runoff", "surface-runoff.txt"),
        ("--ice-thickness", "ice-thickness.txt"),
        ("--basal-ice-velocity", "basal-ice-velocity.txt"),
    ):
        command.extend((option, str(fields / name)))
    subprocess.run(command, check=True)


def newest(path: Path, pattern: str) -> Path:
    candidates = sorted(path.rglob(pattern))
    if not candidates:
        raise RuntimeError(f"no {pattern} was written below {path}")
    return candidates[-1]


def surface_statistics(surface: Path) -> dict[str, float]:
    with surface.open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    result = {}
    for column in (
        "elevation_change_m",
        "glacial_erosion_m",
        "sediment_flux_m3_per_year",
        "marine_sediment_flux_m3_per_year",
    ):
        values = np.array([float(row[column]) for row in rows])
        result[f"maximum_{column}"] = float(np.max(values))
        result[f"sum_{column}"] = float(np.sum(values))
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=COOKBOOK / "output-physical-loop"
    )
    parser.add_argument("--minimum-free-memory-percent", type=int, default=15)
    arguments = parser.parse_args()
    climate_root = INSTALLATION / "aspect_ClimberX"
    template = climate_root / "tests/yelmo-active-diva"
    climate_executable = climate_root / "sources/climber-x/climber.x"
    aspect_executable = (
        INSTALLATION / "aspect_fatscapecc/builts/fastscape-release/aspect-release"
    )
    for required in (template, climate_executable, aspect_executable, EXCHANGE_TOOL):
        if not required.exists():
            parser.error(f"required local installation is missing: {required}")

    output = arguments.output.resolve()
    baseline_case, feedback_case = (
        output / "climate-baseline",
        output / "climate-feedback",
    )
    baseline_exchange = output / "baseline-climate.cxe"
    feedback_exchange = output / "feedback-climate.cxe"
    topography_exchange = output / "returned-topography.cxe"
    aspect_output, fields = output / "aspect-fastscape", output / "aspect-input"

    prepare_climate_case(template, baseline_case, climate_executable)
    run_climate(
        baseline_case,
        baseline_exchange,
        None,
        climate_root / "local/lib",
        arguments.minimum_free_memory_percent,
    )
    convert_climate(baseline_exchange, fields)
    parameter_file = output / "physical-loop.prm"
    write_aspect_parameters(parameter_file, aspect_output, fields)
    run_monitored(
        [str(aspect_executable), str(parameter_file)],
        INSTALLATION / "aspect_fatscapecc/tests",
        output / "aspect.log",
        os.environ.copy(),
        arguments.minimum_free_memory_percent,
    )

    surface = newest(aspect_output, "surface-*.csv")
    command = [
        sys.executable,
        str(EXCHANGE_TOOL),
        "surface-to-climate",
        "--surface",
        str(surface),
        "--climate",
        str(baseline_exchange),
        "--output",
        str(topography_exchange),
    ]
    polar_history = next(iter(aspect_output.rglob("true_polar_wander.csv")), None)
    if polar_history is not None:
        command.extend(("--polar-wander-history", str(polar_history)))
    subprocess.run(command, check=True)

    prepare_climate_case(template, feedback_case, climate_executable)
    run_climate(
        feedback_case,
        feedback_exchange,
        topography_exchange,
        climate_root / "local/lib",
        arguments.minimum_free_memory_percent,
    )
    plot_environment = os.environ.copy()
    plot_environment["MPLCONFIGDIR"] = str(output / ".matplotlib")
    subprocess.run(
        [
            sys.executable,
            str(PLOT_TOOL),
            "--baseline",
            str(baseline_exchange),
            "--feedback",
            str(feedback_exchange),
            "--topography",
            str(topography_exchange),
            "--surface",
            str(surface),
            "--output",
            str(output / "physical-loop-summary.png"),
        ],
        check=True,
        env=plot_environment,
    )
    summary = surface_statistics(surface)
    baseline = read_exchange(baseline_exchange)
    feedback = read_exchange(feedback_exchange)
    for field in (
        "precipitation_rate",
        "surface_temperature",
        "ice_thickness",
        "basal_ice_velocity",
    ):
        difference = feedback.fields[field] - baseline.fields[field]
        summary[f"maximum_absolute_{field}_change"] = float(np.max(np.abs(difference)))
    summary.update(
        {
            "baseline_exchange": str(baseline_exchange),
            "feedback_exchange": str(feedback_exchange),
            "returned_topography": str(topography_exchange),
            "surface_result": str(surface),
            "polar_wander_history": str(polar_history) if polar_history else None,
        }
    )
    (output / "summary.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
