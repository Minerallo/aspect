COOKBOOK = Path(__file__).resolve().parent
ASPECT_SOURCE = COOKBOOK.parents[1]
INSTALLATION = ASPECT_SOURCE.parent.parent
EXCHANGE_TOOL = (
    ASPECT_SOURCE / "contrib/coupling/climberx_fastscape/surface_exchange.py"
)
PLOT_TOOL = COOKBOOK / "plot_physical_loop.py"
sys.path.insert(0, str(EXCHANGE_TOOL.parent))
